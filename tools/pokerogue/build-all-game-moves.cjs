#!/usr/bin/env node
/**
 * Builds data/mods/pokerogue/all-game-moves.ts: for every PokéRogue Pokémon,
 * the moves it has learnt in any game that aren't already in its PokéRogue
 * move list. The PokéRogue formats with the "PokeRogue All Moves" rule allow
 * them (Chaos doesn't have the rule).
 *
 * "Any game": the main data (Gens 3-9: level-up, TM, tutor, egg, event and
 * transfer moves), Gens 1-2, Let's Go, BDSP, Legends: Arceus, Legends: Z-A,
 * Pokémon Champions, and the older versions of games the server keeps
 * (FRLG, Ruby/Sapphire, Platinum, BW1, XY, Sun/Moon, Sword/Shield DLC 1,
 * Scarlet/Violet before and after DLC). Pre-evolutions' moves count, and
 * forms use their base form's moves where a game has none of their own
 * (the same way the server's validator works out a move pool).
 *
 * Only moves the PokéRogue formats can use are kept (no Z-Moves / Max Moves,
 * nothing CAP or otherwise nonexistent).
 *
 * Usage: node build && node tools/pokerogue/build-all-game-moves.cjs [--report file.json]
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../..');
process.chdir(ROOT);
const {Dex, toID} = require(path.join(ROOT, 'dist/sim/dex'));

const SOURCE_MODS = [
	'gen2', 'gen3rs', 'gen3frlg', 'gen4pt', 'gen5bw1', 'gen6xy', 'gen7sm', 'gen7letsgo',
	'gen8dlc1', 'gen8bdsp', 'gen8legends', 'gen9predlc', 'gen9dlc1', 'gen9legends', 'champions',
];

const prDex = Dex.mod('pokerogue');

// raw move lists of each game (read straight from the files, without loading those mods)
const tables = [['main', Dex.data.Learnsets]];
for (const mod of SOURCE_MODS) {
	const file = path.join(ROOT, 'dist/data/mods', mod, 'learnsets.js');
	tables.push([mod, require(file).Learnsets]);
}

/** The species whose move lists a Pokémon also gets, like the validator's learnsetParent */
function learnsetParent(species) {
	if (species.prevo) return prDex.species.get(species.prevo);
	if (species.changesFrom && species.baseSpecies !== 'Kyurem') return prDex.species.get(species.changesFrom);
	if (species.baseSpecies !== species.name && prDex.species.get(species.baseSpecies).prevo) {
		// e.g. Cap Pikachu: its line's first stage
		let base = prDex.species.get(species.baseSpecies);
		while (base.prevo) base = prDex.species.get(base.prevo);
		return base;
	}
	return null;
}

/** Every move a species (and its pre-evolutions / base form) learns in one game's move lists */
function gameMoves(table, speciesid, out) {
	let species = prDex.species.get(speciesid);
	const seen = new Set();
	while (species?.exists && !seen.has(species.id)) {
		seen.add(species.id);
		const learnset = table[species.id]?.learnset;
		if (learnset) {
			for (const moveid in learnset) out.add(moveid);
			species = learnsetParent(species);
		} else if ((species.changesFrom || species.baseSpecies) !== species.name) {
			// a form without its own move list in this game
			species = prDex.species.get(species.changesFrom || species.baseSpecies);
		} else if (species.prevo) {
			species = prDex.species.get(species.prevo);
		} else {
			break;
		}
	}
}

function usable(moveid) {
	const move = prDex.moves.get(moveid);
	if (!move.exists || move.isZ || move.isMax || move.id === 'struggle') return false;
	return !move.isNonstandard || move.isNonstandard === 'Past' || move.isNonstandard === 'Unobtainable';
}

const extra = {};
const report = {};
let total = 0;
for (const id of Object.keys(prDex.data.Learnsets).sort()) {
	const entry = prDex.data.Learnsets[id];
	if (!entry.pokeRogue || !entry.learnset) continue;
	const all = new Set();
	const byGame = {};
	for (const [game, table] of tables) {
		const moves = new Set();
		gameMoves(table, id, moves);
		for (const moveid of moves) {
			if (!usable(moveid) || entry.learnset[moveid] || all.has(moveid)) continue;
			all.add(moveid);
			byGame[moveid] = game;
		}
	}
	if (!all.size) continue;
	extra[id] = [...all].sort();
	report[id] = byGame;
	total += all.size;
}

let out = `/*
 * GENERATED by tools/pokerogue/build-all-game-moves.cjs. Do not edit by hand;
 * re-run the tool to update.
 *
 * Moves each PokéRogue Pokémon has learnt in any game that aren't in its
 * PokéRogue move list (species id -> move ids, separated by spaces). Formats
 * with the "PokeRogue All Moves" rule allow them.
 */

export const AllGameMoves: {[speciesid: string]: string} = {\n`;
for (const id in extra) out += `\t${id}: "${extra[id].join(' ')}",\n`;
out += `};\n`;
fs.writeFileSync(path.join(ROOT, 'data/mods/pokerogue/all-game-moves.ts'), out);
console.log(`${Object.keys(extra).length} Pokémon get ${total} moves in all ` +
	`(${(out.length / 1024).toFixed(0)} KB): data/mods/pokerogue/all-game-moves.ts`);

const reportIndex = process.argv.indexOf('--report');
if (reportIndex > 0) fs.writeFileSync(process.argv[reportIndex + 1], JSON.stringify(report));
